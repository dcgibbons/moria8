#importonce
// cache_layout.s — Shared boot/runtime Sideways RAM cache layout (Banks 5-7).
// Authority: docs/BBCMASTER_MEMORY_CONTRACT.md.
//
// Bank 5 ($8000-$BFFF):
//   $8000-$B30B  Live 198x66 Map (13,068 B)
//   $B400-$BDFF  Cached OVL.UI (10 pages = 2,560 B)
//
// Bank 6 ($8000-$BFFF):
//   $8000-$96FF  BeebAuxData (23 pages = 5,888 B, virtual $6000-$76FF)
//   $9700-$ACFF  Cached OVL.TOWN (22 pages = 5,632 B)
//   $AD00-$B9FF  Cached OVL.MODAL (13 pages = 3,328 B)
//   $BA00-$BDFF  Cached MONSTER.DB1 (4 pages = 1,024 B)
//
// Bank 7 ($8000-$BFFF):
//   $8000-$94FF  Cached OVL.SPELL (21 pages = 5,376 B)
//   $9500-$A9FF  Cached OVL.ITEMS (21 pages = 5,376 B)
//   $AA00-$BDFF  Cached OVL.GEN (20 pages = 5,120 B)

.const BEEB_CACHE_UI_BANK    = $05
.const BEEB_CACHE_UI_ADDR    = $b400
.const BEEB_CACHE_UI_PAGES   = 10

.const BEEB_CACHE_AUX_BANK   = $06
.const BEEB_CACHE_AUX_ADDR   = $8000
.const BEEB_CACHE_AUX_PAGES  = 23

.const BEEB_CACHE_TOWN_BANK  = $06
.const BEEB_CACHE_TOWN_ADDR  = $9700
.const BEEB_CACHE_TOWN_PAGES = 22

.const BEEB_CACHE_MODAL_BANK  = $06
.const BEEB_CACHE_MODAL_ADDR  = $ad00
.const BEEB_CACHE_MODAL_PAGES = 13

.const BEEB_CACHE_DB1_BANK   = $06
.const BEEB_CACHE_DB1_ADDR   = $ba00
.const BEEB_CACHE_DB1_PAGES  = 4

.const BEEB_CACHE_SPELL_BANK  = $07
.const BEEB_CACHE_SPELL_ADDR  = $8000
.const BEEB_CACHE_SPELL_PAGES = 21

.const BEEB_CACHE_ITEMS_BANK  = $07
.const BEEB_CACHE_ITEMS_ADDR  = $9500
.const BEEB_CACHE_ITEMS_PAGES = 21

.const BEEB_CACHE_GEN_BANK   = $07
.const BEEB_CACHE_GEN_ADDR   = $aa00
.const BEEB_CACHE_GEN_PAGES  = 20

.const BEEB_SWR_BANK_UI      = BEEB_CACHE_UI_BANK
.const BEEB_SWR_ADDR_UI      = BEEB_CACHE_UI_ADDR
.const BEEB_SWR_PAGES_UI     = BEEB_CACHE_UI_PAGES

.const BEEB_SWR_BANK_TOWN    = BEEB_CACHE_TOWN_BANK
.const BEEB_SWR_ADDR_TOWN    = BEEB_CACHE_TOWN_ADDR
.const BEEB_SWR_PAGES_TOWN   = BEEB_CACHE_TOWN_PAGES

.const BEEB_SWR_BANK_MODAL   = BEEB_CACHE_MODAL_BANK
.const BEEB_SWR_ADDR_MODAL   = BEEB_CACHE_MODAL_ADDR
.const BEEB_SWR_PAGES_MODAL  = BEEB_CACHE_MODAL_PAGES

.const BEEB_SWR_BANK_MON1    = BEEB_CACHE_DB1_BANK
.const BEEB_SWR_ADDR_MON1    = BEEB_CACHE_DB1_ADDR
.const BEEB_SWR_PAGES_MON1   = BEEB_CACHE_DB1_PAGES

.const BEEB_SWR_BANK_SPELL   = BEEB_CACHE_SPELL_BANK
.const BEEB_SWR_ADDR_SPELL   = BEEB_CACHE_SPELL_ADDR
.const BEEB_SWR_PAGES_SPELL  = BEEB_CACHE_SPELL_PAGES

.const BEEB_SWR_BANK_ITEMS   = BEEB_CACHE_ITEMS_BANK
.const BEEB_SWR_ADDR_ITEMS   = BEEB_CACHE_ITEMS_ADDR
.const BEEB_SWR_PAGES_ITEMS  = BEEB_CACHE_ITEMS_PAGES

.const BEEB_SWR_BANK_GEN     = BEEB_CACHE_GEN_BANK
.const BEEB_SWR_ADDR_GEN     = BEEB_CACHE_GEN_ADDR
.const BEEB_SWR_PAGES_GEN    = BEEB_CACHE_GEN_PAGES

.assert "Bank 5 UI cache starts after MAP_END ($B30B)", BEEB_CACHE_UI_ADDR > $b30b, true
.assert "Bank 5 UI cache fits below $C000", BEEB_CACHE_UI_ADDR + BEEB_CACHE_UI_PAGES * $100 <= $c000, true
.assert "Bank 6 slots are contiguous and fit below $C000", BEEB_CACHE_AUX_ADDR + BEEB_CACHE_AUX_PAGES * $100 == BEEB_CACHE_TOWN_ADDR && BEEB_CACHE_TOWN_ADDR + BEEB_CACHE_TOWN_PAGES * $100 == BEEB_CACHE_MODAL_ADDR && BEEB_CACHE_MODAL_ADDR + BEEB_CACHE_MODAL_PAGES * $100 == BEEB_CACHE_DB1_ADDR && BEEB_CACHE_DB1_ADDR + BEEB_CACHE_DB1_PAGES * $100 <= $c000, true
.assert "Bank 7 slots are contiguous and fit below $C000", BEEB_CACHE_SPELL_ADDR + BEEB_CACHE_SPELL_PAGES * $100 == BEEB_CACHE_ITEMS_ADDR && BEEB_CACHE_ITEMS_ADDR + BEEB_CACHE_ITEMS_PAGES * $100 == BEEB_CACHE_GEN_ADDR && BEEB_CACHE_GEN_ADDR + BEEB_CACHE_GEN_PAGES * $100 <= $c000, true
